const DAY_LABEL_KEYS = {
	Sun: 'sunday',
	Mon: 'monday',
	Tue: 'tuesday',
	Wed: 'wednesday',
	Thu: 'thursday',
	Fri: 'friday',
	Sat: 'saturday',
};

export function getLocatorLabels(code) {
	return LOCATOR_LANGUAGES[code] || LOCATOR_LANGUAGES.en;
}

export function formatLocationsFound(count, labels) {
	const template = count === 1 ? labels.locationFoundNearYou : labels.locationsFoundNearYou;
	return template.replace('{count}', String(count));
}

export function dayLabelKey(dayKey) {
	return DAY_LABEL_KEYS[dayKey] || 'monday';
}
